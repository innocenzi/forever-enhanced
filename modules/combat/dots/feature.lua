-- Damage Over Time to Come: shows, on the target frame's health bar and
-- on enemy nameplates, the part of a unit's health the player's damage over
-- time effects have yet to take.
--
-- Forever hides the target's auras and the combat log from addons in combat,
-- and every unit's health at all times. So the damage is predicted from the
-- player's own casts (tracker.lua), with what each deals from the client's
-- data and measurements in game (spells.lua), and drawn over the health bar's
-- fill without ever reading the health (overlays.lua).
--
-- Files of this slice:
--   feature.lua   registration and lifecycle (this file)
--   locales.lua   strings
--   data.lua      generated by `bun run dots`: the spells followed, their talents
--                 and amplifiers, from the client's data
--   measured.lua  what the data doesn't say (attack power), measured in game
--   spells.lua    the spells followed and what one cast deals
--   stats.lua     the player's attack power and talents, read out of combat
--   tracker.lua   the player's effects on each unit, from their casts
--   overlays.lua  the damage to come, drawn on health bars

local _, ns = ...

local DoTs = ns:RegisterFeature("combat", "dots", {
    order = 3,
    presets = {
        minimal = { enabled = false },
        enhanced = { enabled = true },
    },
})

function DoTs:OnEnable()
    self.Stats:Enable()
    self.Tracker:Enable()
    self.Overlays:Enable()
end

function DoTs:OnDisable()
    self.Overlays:Disable()
    self.Tracker:Disable()
    self.Stats:Disable()
end
