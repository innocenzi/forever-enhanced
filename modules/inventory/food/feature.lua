-- Food on action bars: an action slot holding food or drink keeps the best one
-- of that kind in the bags. Putting food on a slot makes it a food slot, moving
-- or removing the food moves or removes it. Like retail's, the client is
-- expected to keep an item in its slot at a count of 0 (unmeasured on
-- Forever), so nothing is saved but the kind of the slots holding an item that
-- is both food and drink (slots.lua).
--
-- "pick": which usable item a slot gets: the one restoring the most ("level"),
-- the cheapest, or the one the bags hold the most or the least of. Conjured
-- food and water always come first.
-- "buffFood": whether buff food (Well Fed) counts; when it doesn't, a slot
-- holding it is left alone.
--
-- Action slots can't change in combat (food can't be eaten then either): swaps
-- wait for it to end, and for the cursor to be empty.
--
-- Files of this slice:
--   feature.lua  registration, schema, lifecycle and the choice of the best item (this file)
--   locales.lua  strings
--   data.lua     what each food and drink restores (generated by tools/food.ts)
--   slots.lua    the slots holding food and drink, and the swaps

local _, ns = ...

local Food = ns:RegisterFeature("inventory", "food", {
    order = 10,
    enabledByDefault = false,
    settings = {
        {
            key = "pick",
            type = "dropdown",
            default = "level",
            options = { "level", "cheapest", "largest", "smallest" },
        },
        { key = "buffFood", type = "toggle", default = false },
    },
    presets = {
        minimal = { enabled = false },
        enhanced = { enabled = true, pick = "level", buffFood = false },
    },
})

function Food:OnEnable()
    self.Slots:Enable()
end

function Food:OnDisable()
    self.Slots:Disable()
end

function Food:OnSettingChanged()
    self.Slots:Refresh()
end

-- The item's entry in data.lua, or nil for an item that isn't food or drink,
-- or buff food while it doesn't count.
function Food:GetItem(itemID)
    local item = self.Data[itemID]
    if item and (not item.buff or self.db.buffFood) then
        return item
    end
    return nil
end

-- Public API: whether itemID is food or drink, buff food included. The data doesn't depend
-- on the feature being on: other features read it too (inventory.cheapest).
function Food:IsFoodOrDrink(itemID)
    return self.Data[itemID] ~= nil
end

-- Choosing ---------------------------------------------------------------------------

-- What candidates are ranked by, in turn: each returns a number, higher being better.
local function Conjured(candidate)
    return candidate.item.conjured and 1 or 0
end

local function Restores(candidate)
    return candidate.restores
end

local function Level(candidate)
    return candidate.item.level
end

local function Cheapness(candidate)
    return -candidate.item.price
end

local function Count(candidate)
    return candidate.count
end

local function Fewness(candidate)
    return -candidate.count
end

-- By "pick" setting.
local CRITERIA = {
    level = { Conjured, Restores, Level },
    cheapest = { Conjured, Cheapness, Restores },
    largest = { Conjured, Count, Restores },
    smallest = { Conjured, Fewness, Restores },
}

local function IsBetter(a, b, criteria)
    for _, criterion in ipairs(criteria) do
        local valueA, valueB = criterion(a), criterion(b)
        if valueA ~= valueB then
            return valueA > valueB
        end
    end
    -- The same item every time.
    return a.itemID < b.itemID
end

-- The item ID of the best `kind` ("food" or "drink") among `counts` (item ID ->
-- count in the bags) for a player of `level`, or nil when none fits.
function Food:PickBest(kind, counts, level)
    local criteria = CRITERIA[self.db.pick]
    local best
    for itemID, count in pairs(counts) do
        local item = self:GetItem(itemID)
        if item and item[kind] and item.level <= level and count > 0 then
            local candidate = { itemID = itemID, item = item, count = count, restores = item[kind] }
            if not best or IsBetter(candidate, best, criteria) then
                best = candidate
            end
        end
    end
    return best and best.itemID
end
