-- Exploration: a button in the world map's top right corner, under Blizzard's own,
-- showing whether the map in view is fully explored, and on hover which of its parts
-- are and which are missing. On a zone, its areas (its explored-area overlays: the
-- client lists the explored ones, data.lua every one); on a continent, its zones; on
-- the world, its continents. On map.seamless's view too: the map it shows.
--
-- TAINT: the button is a frame of ours over Blizzard's map. It only reads Blizzard's
-- map (its map ID, the buttons it anchors under), never writes into it.
--
-- Files of this slice:
--   feature.lua   registration and lifecycle (this file)
--   locales.lua   strings
--   data.lua      generated by tools/exploration.ts: every zone art's overlays and their areas
--   progress.lua  what's explored of a map
--   button.lua    the button and its tooltip

local _, ns = ...

local Exploration = ns:RegisterFeature("map", "exploration", {
    order = 3,
    presets = {
        minimal = { enabled = false },
        enhanced = { enabled = true },
    },
})

function Exploration:OnEnable()
    self.Button:Enable()
end

function Exploration:OnDisable()
    self.Button:Disable()
end
