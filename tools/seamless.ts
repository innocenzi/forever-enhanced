// Generates the seamless world map's data and masks (modules/map/seamless):
//   data.lua          every zone art's explored-area pieces, from the Forever client's
//                     DB2 tables (WorldMapOverlay + WorldMapOverlayTile, on Azeroth's
//                     maps) as exported by wago.tools; which zones have their share and
//                     their tints, which continents have their land, the papers' sizes
//   media/zone/*.png  each zone's share of the world (tools/seamless/ownership.ts), made
//                     from OpenMap's zone masks (MIT, github.com/openmap-world/openmap, at
//                     OPENMAP_COMMIT: each zone's territory, frame and land, traced from the
//                     zone maps) and where the game places the zones (DB2)
//   media/land/*.png  each continent's land, but off the sea the zones paint (from OpenMap's
//                     MapBackLand, traced from its map)
//   media/land.png,   blank map paper and sea for places no zone's map covers: patches of
//   media/sea.png     the zone maps' own blank parchment and open sea, made to tile
//                     (tools/seamless/paper.ts)
//   media/*.png       OpenMap's edge fades the map still uses
// OpenMap ships its masks as uncompressed 32-bit TGA; they're written here as PNG
// (lossless, 10 to 50 times smaller). Everything is made before media/ is replaced, so a
// failed download leaves it as it was.
//
//   bun run seamless                    latest Forever (wowf) build
//   bun run seamless --build 1.60.1.70888
//   bun run seamless --refresh          download again instead of using tools/.cache
//
// `bun tools/seamless/preview.ts` renders part of the result out of the game.

import { mkdir, rename, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { latestBuild } from "./wago";
import { decodePng, decodeTga, encodePng, type Image } from "./seamless/images";
import { continentLand, type MaskSources, ownershipMasks } from "./seamless/ownership";
import { findPapers, type Paper } from "./seamless/paper";
import { Downloads, loadTables, OPENMAP_COMMIT, type Piece, parseTints, type Tint, World } from "./seamless/world";

const SLICE = "modules/map/seamless";

// OpenMap's edge fades the map uses -> the slice's names.
const FEATHERS = {
    MapFeatherThin: "feather-thin",
    MapFeatherWide: "feather-wide",
    MapFeatherRound: "feather-round",
} as const;

function renderLua(
    pieces: Map<number, Piece[]>,
    zones: number[],
    tints: Map<number, Tint>,
    lands: number[],
    papers: { land: Paper; sea: Paper },
    build: string,
): string {
    const lines = [
        `-- Generated by tools/seamless.ts (build ${build}, OpenMap ${OPENMAP_COMMIT.slice(0, 7)}). Do not edit.`,
        "-- Pieces: UiMapArtID -> its explored-area pieces, { width, height, offsetX, offsetY, fileIDs... }.",
        "-- Zones: the zones (uiMapID) that have their share of the world, media/zone/<uiMapID>.png.",
        "-- Lands: the continents (uiMapID) that have their land, media/land/<uiMapID>.png.",
        "-- Papers: the world units each blank paper tile spans (media/land.png, media/sea.png),",
        `-- at its map's scale: land from ${papers.land.from}, sea from ${papers.sea.from}.`,
        "-- Tints: uiMapID -> { r, g, b } multipliers taking its colours toward the palette every zone",
        "-- shares (OpenMap's colour matching, Data/Forever/Grade.lua).",
        "",
        "local _, ns = ...",
        "",
        'local Seamless = ns:GetFeature("map", "seamless")',
        "",
        "Seamless.Pieces = {",
        ...[...pieces.keys()]
            .sort((a, b) => a - b)
            .map((art) => `    [${art}] = { ${pieces.get(art)!.map((piece) => `{ ${piece.join(", ")} }`).join(", ")} },`),
        "}",
        "",
        `Seamless.Zones = { ${zones.map((id) => `[${id}] = true`).join(", ")} }`,
        "",
        `Seamless.Lands = { ${lands.map((id) => `[${id}] = true`).join(", ")} }`,
        "",
        `Seamless.Papers = { land = ${papers.land.worldSize.toFixed(2)}, sea = ${papers.sea.worldSize.toFixed(2)} }`,
        "",
        "Seamless.Tints = {",
        ...zones.map((id) => `    [${id}] = { ${tints.get(id)!.join(", ")} },`),
        "}",
        "",
    ];
    return lines.join("\n");
}

/** `image` as PNG, after checking it decodes to the same pixels. */
function png(name: string, image: Image): Uint8Array {
    const data = encodePng(image);
    const back = decodePng(data);
    if (back.width !== image.width || back.height !== image.height || Buffer.compare(back.rgba, image.rgba) !== 0) {
        throw new Error(`${name}: the PNG doesn't decode to the same pixels`);
    }
    return data;
}

function buildArgument(args: string[]): string | undefined {
    const index = args.indexOf("--build");
    if (index < 0) return undefined;
    const build = args[index + 1];
    if (!build || build.startsWith("--")) {
        throw new Error("--build needs a build, e.g. --build 1.60.1.70888");
    }
    return build;
}

if (import.meta.main) {
    const args = Bun.argv.slice(2);
    const build = buildArgument(args) ?? (await latestBuild());
    const repoRoot = path.resolve(import.meta.dir, "..");
    const downloads = new Downloads(repoRoot, args.includes("--refresh"));
    const world = new World(await loadTables(downloads, build));

    // OpenMap's territory, frame and land of each zone.
    const textures = await downloads.openMapTextures();
    const sources: MaskSources = { territory: new Map(), edge: new Map(), land: new Map() };
    for (const [folder, kind] of [
        ["MapTerritory", "territory"],
        ["MapEdge", "edge"],
        ["MapZoneLand", "land"],
    ] as const) {
        for (const file of textures) {
            const match = file.match(new RegExp(`^${folder}/(\\d+)\\.tga$`));
            if (match) {
                sources[kind].set(Number(match[1]), decodeTga(await downloads.openMapFile(file)));
            }
        }
    }

    // Every file of media/ (its path in it -> PNG), made before anything is written.
    const files = new Map<string, Uint8Array>();
    const zones = world.zones();
    const { masks, field } = ownershipMasks(world, zones, sources);
    for (const [mapID, mask] of masks) {
        files.set(`zone/${mapID}.png`, png(`zone ${mapID}`, mask));
    }
    const lands: number[] = [];
    for (const mapID of world.mapsOfType("continent")) {
        if (textures.includes(`MapBackLand/${mapID}.tga`)) {
            const backLand = decodeTga(await downloads.openMapFile(`MapBackLand/${mapID}.tga`));
            files.set(`land/${mapID}.png`, png(`land ${mapID}`, continentLand(world, mapID, backLand, field)));
            lands.push(mapID);
        }
    }
    const papers = await findPapers(world, downloads, build, sources);
    files.set("land.png", png("land paper", papers.land.image));
    files.set("sea.png", png("sea paper", papers.sea.image));
    for (const [name, file] of Object.entries(FEATHERS)) {
        files.set(`${file}.png`, png(name, decodeTga(await downloads.openMapFile(`${name}.tga`))));
    }
    const tints = parseTints(await downloads.openMapData("Grade.lua"));
    const shared = [...masks.keys()].sort((a, b) => a - b);
    const untinted = shared.filter((id) => !tints.has(id)).map((id) => `${world.name(id)} (${id})`);
    if (untinted.length > 0) {
        throw new Error(`no colour matching in OpenMap's Grade.lua for ${untinted.join(", ")}`);
    }

    // media/ replaced at once: written beside it, then swapped in.
    const media = path.join(repoRoot, SLICE, "media");
    const staged = `${media}.new`;
    await rm(staged, { recursive: true, force: true });
    for (const [file, data] of files) {
        await mkdir(path.dirname(path.join(staged, file)), { recursive: true });
        await writeFile(path.join(staged, file), data);
    }
    await rm(media, { recursive: true, force: true });
    await rename(staged, media);

    const output = path.join(repoRoot, SLICE, "data.lua");
    await writeFile(output, renderLua(world.pieces, shared, tints, lands, papers, build));
    // StyLua's layout, so `bun run lint` passes on the generated file.
    const stylua = Bun.spawnSync(["stylua", output], { stdout: "inherit", stderr: "inherit" });
    if (stylua.exitCode !== 0) {
        throw new Error("stylua failed on the generated file");
    }

    const without = zones.filter((id) => !sources.territory.has(id)).map((id) => `${world.name(id)} (${id})`);
    const count = [...world.pieces.values()].reduce((sum, list) => sum + list.length, 0);
    const bytes = [...files.values()].reduce((sum, data) => sum + data.length, 0);
    console.log(`${SLICE}/data.lua: ${world.pieces.size} zone arts, ${count} pieces, ${masks.size} zones (build ${build})`);
    console.log(`${SLICE}/media: ${Math.round(bytes / 1024)} KB of PNG`);
    if (without.length > 0) {
        console.log(`zones without OpenMap's territory (their whole map, less a thin border): ${without.join(", ")}`);
    }
}
