// Generates modules/interface/icons/data.lua: the name of every icon of the
// Forever client (the files in Interface\Icons), by file ID, from its own DB2
// table ManifestInterfaceData as exported by wago.tools. The macro icon picker
// only gets file IDs from the client (GetMacroIcons), so the names are what
// its search box matches.
//
//   bun run icons                   latest Forever (wowf) build
//   bun run icons --build 1.60.1.70888
//   bun run icons --refresh         download again instead of using tools/.cache

import { writeFile } from "node:fs/promises";
import path from "node:path";
import { integer, latestBuild, parseCsv, table } from "./wago";

const OUTPUT = "modules/interface/icons/data.lua";
const CACHE = "tools/.cache/icons";

const ICONS_FOLDER = "interface\\icons\\";

/** File ID → icon name (lowercase, without its extension), sorted by file ID. */
export function collectIcons(manifestCsv: string): [number, string][] {
    const icons: [number, string][] = [];
    for (const row of parseCsv(manifestCsv)) {
        if (row.FilePath.toLowerCase() !== ICONS_FOLDER) {
            continue;
        }
        const name = row.FileName.toLowerCase()
            .replace(/\.blp$/, "")
            .trim();
        // One line per icon in a long string, uppercase marking where the name starts (see renderLua).
        if (name === "" || /[A-Z\r\n]|\]\]/.test(name)) {
            throw new Error(`Unexpected icon name '${row.FileName}'`);
        }
        icons.push([integer(row, "ID"), name]);
    }
    if (icons.length === 0) {
        throw new Error("No icons in ManifestInterfaceData: its columns changed?");
    }
    return icons.sort((a, b) => a[0] - b[0]);
}

// The longest start a name can share with the one before: A to Z.
const MAX_SHARED = 25;

/**
 * The icons sorted by name, one per line: the file ID in base 36, a letter
 * telling how many characters the name shares with the line before (A for
 * none, B for one...), then the rest of the name. Most names share a long
 * start ("inv_misc_"), so this is well under half the plain list.
 */
export function encodeIcons(icons: [number, string][]): string {
    const sorted = [...icons].sort((a, b) => (a[1] < b[1] ? -1 : a[1] > b[1] ? 1 : a[0] - b[0]));
    let previous = "";
    return sorted
        .map(([id, name]) => {
            let shared = 0;
            while (shared < MAX_SHARED && shared < previous.length && previous[shared] === name[shared]) {
                shared++;
            }
            previous = name;
            return id.toString(36) + String.fromCharCode(65 + shared) + name.slice(shared);
        })
        .join("\n");
}

// One long string rather than a table: it costs a single string, which a
// search reads through without keeping more.
export function renderLua(icons: [number, string][], build: string): string {
    return [
        `-- Generated by tools/icons.ts from Forever's DB2 tables (build ${build}). Do not edit.`,
        "-- Every icon's name (Interface\\Icons, lowercase), encoded by tools/icons.ts (encodeIcons).",
        "",
        "local _, ns = ...",
        "",
        'local Icons = ns:GetFeature("interface", "icons")',
        "",
        "Icons.NAMES = [[",
        encodeIcons(icons),
        "]]",
        "",
    ].join("\n");
}

async function main() {
    const args = process.argv.slice(2);
    const buildIndex = args.indexOf("--build");
    const build = buildIndex >= 0 ? args[buildIndex + 1] : await latestBuild();
    const refresh = args.includes("--refresh");

    const repoRoot = path.resolve(import.meta.dir, "..");

    const icons = collectIcons(await table(path.join(repoRoot, CACHE), "ManifestInterfaceData", build, refresh));
    await writeFile(path.join(repoRoot, OUTPUT), renderLua(icons, build));
    console.log(`Wrote ${icons.length} icons to ${OUTPUT} (build ${build})`);
}

if (import.meta.main) {
    await main();
}
