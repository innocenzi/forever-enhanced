// Generates modules/map/exploration/data.lua: every zone art's explored-area overlays
// and the areas each one shows, from the Forever client's DB2 tables (WorldMapOverlay,
// on Azeroth's maps, as tools/seamless.ts reads them for its pieces) as exported by
// wago.tools. The client lists only the overlays already explored
// (C_MapExplorationInfo.GetExploredMapTextures): these are the rest, matched to them by
// size and offset.
//
//   bun run exploration                    latest Forever (wowf) build
//   bun run exploration --build 1.60.1.70888
//   bun run exploration --refresh          download again instead of using tools/.cache

import { writeFile } from "node:fs/promises";
import path from "node:path";
import { latestBuild } from "./wago";
import { Downloads, loadTables, type Overlay, World } from "./seamless/world";

const OUTPUT = "modules/map/exploration/data.lua";

function renderLua(overlays: Map<number, Overlay[]>, build: string): string {
    const lines = [
        `-- Generated by tools/exploration.ts (build ${build}). Do not edit.`,
        "-- Overlays: UiMapArtID -> its explored-area overlays, { width, height, offsetX, offsetY, areaIDs... }.",
        "",
        "local _, ns = ...",
        "",
        'local Exploration = ns:GetFeature("map", "exploration")',
        "",
        "Exploration.Overlays = {",
        ...[...overlays.keys()]
            .sort((a, b) => a - b)
            .map((art) => `    [${art}] = { ${overlays.get(art)!.map((overlay) => `{ ${overlay.join(", ")} }`).join(", ")} },`),
        "}",
        "",
    ];
    return lines.join("\n");
}

function buildArgument(args: string[]): string | undefined {
    const index = args.indexOf("--build");
    if (index < 0) return undefined;
    const build = args[index + 1];
    if (!build || build.startsWith("--")) {
        throw new Error("--build needs a build, e.g. --build 1.60.1.70888");
    }
    return build;
}

if (import.meta.main) {
    const args = Bun.argv.slice(2);
    const build = buildArgument(args) ?? (await latestBuild());
    const repoRoot = path.resolve(import.meta.dir, "..");
    const world = new World(await loadTables(new Downloads(repoRoot, args.includes("--refresh")), build));
    const nameless = [...world.overlays].filter(([, list]) => list.some((overlay) => overlay.length <= 4));
    if (nameless.length > 0) {
        throw new Error(`overlays without an area on arts ${nameless.map(([art]) => art).join(", ")}`);
    }

    const output = path.join(repoRoot, OUTPUT);
    await writeFile(output, renderLua(world.overlays, build));
    // StyLua's layout, so `bun run lint` passes on the generated file.
    const stylua = Bun.spawnSync(["stylua", output], { stdout: "inherit", stderr: "inherit" });
    if (stylua.exitCode !== 0) {
        throw new Error("stylua failed on the generated file");
    }

    const count = [...world.overlays.values()].reduce((sum, list) => sum + list.length, 0);
    console.log(`${OUTPUT}: ${world.overlays.size} zone arts, ${count} overlays (build ${build})`);
}
