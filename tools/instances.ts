// Generates modules/quests/helpers/data.lua: for each dungeon and raid map, the
// areas its quests are filed under in the quest log, from the Forever client's
// own DB2 tables (Map + AreaTable) as exported by wago.tools. The quest log
// names headers after areas, in words that match neither the instance's name nor
// the zone text inside it ("La Prison" for "Prison de Hurlevent"), so quests
// are matched to the instance by area ID instead.
//
//   bun run instances                   latest Forever (wowf) build
//   bun run instances --build 1.60.1.70888
//   bun run instances --refresh         download again instead of using tools/.cache

import { writeFile } from "node:fs/promises";
import path from "node:path";
import { integer, latestBuild, parseCsv, table } from "./wago";

const OUTPUT = "modules/quests/helpers/data.lua";
const CACHE = "tools/.cache/quests";

// Map.InstanceType: 1 for a dungeon, 2 for a raid.
const INSTANCE_TYPES = [1, 2];

/**
 * Instance map ID → the areas its quests can be filed under:
 * - the map's own area (Map.AreaTableID, unset on many old dungeons),
 * - the top-level areas on the map (the only link for those),
 * - areas outside instances, inside a zone, named like the map or its area:
 *   the quest log files Gnomeregan's quests under the Gnomeregan of Dun Morogh,
 *   not the instance's own.
 */
export function collectAreas(mapCsv: string, areaTableCsv: string): Map<number, number[]> {
    const maps = parseCsv(mapCsv).filter((row) => INSTANCE_TYPES.includes(integer(row, "InstanceType")));
    const instanceMaps = new Set(maps.map((row) => integer(row, "ID")));
    const areas = parseCsv(areaTableCsv).map((row) => ({
        id: integer(row, "ID"),
        name: row.AreaName_lang,
        mapID: integer(row, "ContinentID"),
        parentID: integer(row, "ParentAreaID"),
    }));
    const areaNames = new Map(areas.map((area) => [area.id, area.name]));

    const result = new Map<number, number[]>();
    for (const map of maps) {
        const mapID = integer(map, "ID");
        const ids = new Set<number>();
        const ownArea = integer(map, "AreaTableID");
        if (ownArea > 0) {
            ids.add(ownArea);
        }
        for (const area of areas) {
            if (area.mapID === mapID && area.parentID === 0) {
                ids.add(area.id);
            }
        }
        const names = new Set([map.MapName_lang, areaNames.get(ownArea)].filter((name) => name));
        for (const area of areas) {
            if (area.parentID !== 0 && !instanceMaps.has(area.mapID) && names.has(area.name)) {
                ids.add(area.id);
            }
        }
        if (ids.size > 0) {
            result.set(mapID, [...ids].sort((a, b) => a - b));
        }
    }
    return result;
}

export function renderLua(areas: Map<number, number[]>, build: string): string {
    const mapIDs = [...areas.keys()].sort((a, b) => a - b);
    const lines = [
        `-- Generated by tools/instances.ts from Forever's DB2 tables (build ${build}). Do not edit.`,
        "-- Instance map ID (GetInstanceInfo) -> the area IDs its quests' log headers can have.",
        "",
        "local _, ns = ...",
        "",
        'local Helpers = ns:GetFeature("quests", "helpers")',
        "",
        "Helpers.InstanceAreas = {",
        ...mapIDs.map((mapID) => `    [${mapID}] = { ${areas.get(mapID)!.join(", ")} },`),
        "}",
        "",
    ];
    return lines.join("\n");
}

if (import.meta.main) {
    const args = Bun.argv.slice(2);
    const buildIndex = args.indexOf("--build");
    const build = buildIndex >= 0 ? args[buildIndex + 1] : await latestBuild();
    const refresh = args.includes("--refresh");
    const repoRoot = path.resolve(import.meta.dir, "..");

    const areas = collectAreas(
        await table(path.join(repoRoot, CACHE), "Map", build, refresh),
        await table(path.join(repoRoot, CACHE), "AreaTable", build, refresh),
    );
    const output = path.join(repoRoot, OUTPUT);
    await writeFile(output, renderLua(areas, build));
    // StyLua's layout, so `bun run lint` passes on the generated file.
    const stylua = Bun.spawnSync(["stylua", output], { stdout: "inherit", stderr: "inherit" });
    if (stylua.exitCode !== 0) {
        throw new Error("stylua failed on the generated file");
    }
    console.log(`${OUTPUT}: ${areas.size} instances (build ${build})`);
}
