// Generates modules/inventory/crates/data.lua: the components of each Waylaid
// Crate, from the Forever client's own DB2 tables as exported by wago.tools.
//
// A crate's Use spell (ItemXItemEffect -> ItemEffect) builds its description
// on the "Stock Crate" template (CRATE_TEMPLATE_SPELL) and lists the bundles
// that fill it, one line each: "- $M3 Wool Cloth". $Mn is the value of the
// spell's nth effect (SpellEffect, EffectIndex n - 1): the count. The effects
// name no item, so the English name (the export's text) is looked up in
// ItemSparse, deprecated items left out. The tooltip shows the lines in this
// order, which the addon relies on.
//
//   bun run crates                   latest Forever (wowf) build
//   bun run crates --build 1.60.1.70959
//   bun run crates --refresh         download again instead of using tools/.cache

import { writeFile } from "node:fs/promises";
import path from "node:path";
import { float, integer, latestBuild, parseCsv, type Row, table } from "./wago";

const OUTPUT = "modules/inventory/crates/data.lua";
const CACHE = "tools/.cache/crates";

// "Fill the crate with any bundle from the following list:", which every crate's
// Use spell description starts from.
const CRATE_TEMPLATE_SPELL = 1308117;

// ItemSparse.Flags_0: the item no longer exists in the game.
const ITEM_FLAG_DEPRECATED = 0x10;

// "- $M3 Wool Cloth", maybe closed by a color reset.
const COMPONENT = /^- \$M(\d+) (.+?)(?:\|r)?$/;

export type Component = { itemID: number; count: number };

export type Tables = { itemSparse: string; itemXItemEffect: string; itemEffect: string; spell: string; spellEffect: string };

/** Crate item ID -> its components, in the description's order. */
export function collectCrates(tables: Tables): Map<number, Component[]> {
    const items = parseCsv(tables.itemSparse);
    const itemsByName = new Map<string, number[]>();
    for (const row of items) {
        if ((integer(row, "Flags_0") & ITEM_FLAG_DEPRECATED) === 0) {
            const ids = itemsByName.get(row.Display_lang) ?? [];
            ids.push(integer(row, "ID"));
            itemsByName.set(row.Display_lang, ids);
        }
    }
    const descriptions = new Map(parseCsv(tables.spell).map((row) => [integer(row, "ID"), row.Description_lang]));
    const effectsBySpell = new Map<number, Row[]>();
    for (const row of parseCsv(tables.spellEffect)) {
        const spellID = integer(row, "SpellID");
        const effects = effectsBySpell.get(spellID) ?? [];
        effects.push(row);
        effectsBySpell.set(spellID, effects);
    }
    const spellsByEffect = new Map(parseCsv(tables.itemEffect).map((row) => [integer(row, "ID"), integer(row, "SpellID")]));

    const template = `$@spelldesc${CRATE_TEMPLATE_SPELL}`;
    const crates = new Map<number, Component[]>();
    for (const row of parseCsv(tables.itemXItemEffect)) {
        const itemID = integer(row, "ItemID");
        const spellID = spellsByEffect.get(integer(row, "ItemEffectID"));
        const description = spellID !== undefined ? descriptions.get(spellID) : undefined;
        if (!description?.startsWith(template)) {
            continue;
        }
        const components: Component[] = [];
        for (const line of description.split(/\r?\n/).slice(1)) {
            const match = COMPONENT.exec(line.trim());
            if (!match) {
                throw new Error(`Crate ${itemID}: unexpected line '${line}' in spell ${spellID}'s description`);
            }
            const effectIndex = Number(match[1]) - 1;
            const effect = effectsBySpell.get(spellID!)?.find((e) => integer(e, "EffectIndex") === effectIndex);
            if (!effect) {
                throw new Error(`Crate ${itemID}: spell ${spellID} has no effect ${effectIndex} for '${match[2]}'`);
            }
            const ids = itemsByName.get(match[2]) ?? [];
            if (ids.length !== 1) {
                throw new Error(`Crate ${itemID}: '${match[2]}' names ${ids.length} items (${ids.join(", ")})`);
            }
            components.push({ itemID: ids[0], count: float(effect, "EffectBasePointsF") });
        }
        if (components.length === 0) {
            throw new Error(`Crate ${itemID}: spell ${spellID} lists no component`);
        }
        crates.set(itemID, components);
    }
    return crates;
}

export function renderLua(crates: Map<number, Component[]>, build: string): string {
    const itemIDs = [...crates.keys()].sort((a, b) => a - b);
    const lines = [
        `-- Generated by tools/crates.ts from Forever's DB2 tables (build ${build}). Do not edit.`,
        "-- Crate item ID -> its components, in the order of its Use text: { itemID, count }.",
        "",
        "local _, ns = ...",
        "",
        'local Crates = ns:GetFeature("inventory", "crates")',
        "",
        "Crates.Data = {",
        ...itemIDs.map(
            (itemID) =>
                `    [${itemID}] = { ${crates
                    .get(itemID)!
                    .map((c) => `{ ${c.itemID}, ${c.count} }`)
                    .join(", ")} },`,
        ),
        "}",
        "",
    ];
    return lines.join("\n");
}

if (import.meta.main) {
    const args = Bun.argv.slice(2);
    const buildIndex = args.indexOf("--build");
    const build = buildIndex >= 0 ? args[buildIndex + 1] : await latestBuild();
    const refresh = args.includes("--refresh");
    const repoRoot = path.resolve(import.meta.dir, "..");
    const load = (name: string) => table(path.join(repoRoot, CACHE), name, build, refresh);

    const crates = collectCrates({
        itemSparse: await load("ItemSparse"),
        itemXItemEffect: await load("ItemXItemEffect"),
        itemEffect: await load("ItemEffect"),
        spell: await load("Spell"),
        spellEffect: await load("SpellEffect"),
    });
    const output = path.join(repoRoot, OUTPUT);
    await writeFile(output, renderLua(crates, build));
    // StyLua's layout, so `bun run lint` passes on the generated file.
    const stylua = Bun.spawnSync(["stylua", output], { stdout: "inherit", stderr: "inherit" });
    if (stylua.exitCode !== 0) {
        throw new Error("stylua failed on the generated file");
    }
    console.log(`${OUTPUT}: ${crates.size} crates (build ${build})`);
}
